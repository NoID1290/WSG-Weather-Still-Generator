        /// <summary>
        /// Returns true if the HTTP request path is an HLS resource (.m3u8 playlist
        /// or a segment under an /hls/ path). These must NOT be piped as raw MPEG-TS.
        /// </summary>
        private static bool IsHlsPath(string path)
        {
            return path.EndsWith(".m3u8", StringComparison.OrdinalIgnoreCase)
                || path.Contains("/hls/", StringComparison.OrdinalIgnoreCase);
        }

        /// <summary>
        /// Routes an HLS request: .m3u8 playlists are proxied with optional alert
        /// injection; all other HLS resources are proxied transparently to Tunarr.
        /// </summary>
        private async Task HandleHlsRequest(NetworkStream stream, string requestPath, CancellationToken ct)
        {
            if (requestPath.EndsWith(".m3u8", StringComparison.OrdinalIgnoreCase))
            {
                await ProxyHlsPlaylistWithInjection(stream, requestPath, ct);
                return;
            }

            // Regular HLS segment (.ts) — proxy transparently to Tunarr
            await ProxyApiRequestToTunarr(stream, requestPath, ct);
        }

        /// <summary>
        /// Fetches an HLS playlist from Tunarr and, if an alert is active, appends
        /// #EXT-X-DISCONTINUITY + alert segment entries before serving to the client.
        /// </summary>
        private async Task ProxyHlsPlaylistWithInjection(NetworkStream stream, string requestPath, CancellationToken ct)
        {
            try
            {
                string tunarrUrl = $"{_settings.TunarrBaseUrl.TrimEnd('/')}{requestPath}";

                using var response = await _apiProxyClient.GetAsync(tunarrUrl, ct);
                string content = await response.Content.ReadAsStringAsync(ct);

                // Check if alert injection is active and applicable
                string? injBlock = _alertHlsInjectionBlock;
                if (injBlock != null
                    && DateTime.UtcNow.Ticks < Interlocked.Read(ref _alertHlsExpiryTicks)
                    && !content.Contains(AlertHlsSegmentPrefix, StringComparison.OrdinalIgnoreCase))
                {
                    // Only inject if this channel has alerts enabled
                    bool inject = true;
                    var chMatch = Regex.Match(requestPath, @"/stream/channels/([^/.]+)", RegexOptions.IgnoreCase);
                    if (chMatch.Success)
                    {
                        var chState = ResolveChannel(chMatch.Groups[1].Value);
                        if (chState != null && !chState.Config.AlertInterruptEnabled)
                            inject = false;
                    }

                    if (inject)
                    {
                        content = InjectAlertIntoHlsPlaylist(content, injBlock);
                        Logger.Log($"[StreamPipe] HLS proxy: injected alert into {requestPath}", Logger.LogLevel.Debug);
                    }
                }

                byte[] body = Encoding.UTF8.GetBytes(content);

                var sb = new StringBuilder();
                sb.Append($"HTTP/1.1 {(int)response.StatusCode} {response.ReasonPhrase}\r\n");
                sb.Append("Content-Type: application/vnd.apple.mpegurl\r\n");
                sb.Append($"Content-Length: {body.Length}\r\n");
                sb.Append("Cache-Control: no-cache, no-store\r\n");
                sb.Append("Access-Control-Allow-Origin: *\r\n");
                sb.Append("Connection: close\r\n");
                sb.Append("\r\n");

                byte[] headerBytes = Encoding.ASCII.GetBytes(sb.ToString());
                await stream.WriteAsync(headerBytes, 0, headerBytes.Length, ct);
                await stream.WriteAsync(body, 0, body.Length, ct);
                await stream.FlushAsync(ct);
            }
            catch (Exception ex)
            {
                Logger.Log($"[StreamPipe] HLS playlist proxy error for {requestPath}: {ex.Message}", Logger.LogLevel.Warning);
                try
                {
                    string err = "HTTP/1.1 502 Bad Gateway\r\nConnection: close\r\nContent-Length: 0\r\n\r\n";
                    byte[] errBytes = Encoding.ASCII.GetBytes(err);
                    await stream.WriteAsync(errBytes, 0, errBytes.Length, ct);
                }
                catch { }
            }
        }

        /// <summary>
        /// Serves a pre-generated alert HLS segment (.ts) from the local temp directory.
        /// These segments are referenced by the injected playlist entries.
        /// </summary>
        private async Task ServeAlertHlsSegment(NetworkStream stream, string fileName, CancellationToken ct)
        {
            string? dir = _alertHlsDir;
            if (dir == null || !Directory.Exists(dir))
            {
                await SendHttpError(stream, 404, "Not Found", ct);
                return;
            }

            string filePath = Path.Combine(dir, fileName);
            if (!File.Exists(filePath))
            {
                await SendHttpError(stream, 404, "Not Found", ct);
                return;
            }

            try
            {
                byte[] body = await File.ReadAllBytesAsync(filePath, ct);

                var sb = new StringBuilder();
                sb.Append("HTTP/1.1 200 OK\r\n");
                sb.Append("Content-Type: video/mp2t\r\n");
                sb.Append($"Content-Length: {body.Length}\r\n");
                sb.Append("Cache-Control: no-cache\r\n");
                sb.Append("Access-Control-Allow-Origin: *\r\n");
                sb.Append("Connection: close\r\n");
                sb.Append("\r\n");

                byte[] headerBytes = Encoding.ASCII.GetBytes(sb.ToString());
                await stream.WriteAsync(headerBytes, 0, headerBytes.Length, ct);
                await stream.WriteAsync(body, 0, body.Length, ct);
                await stream.FlushAsync(ct);
            }
            catch (Exception ex)
            {
                Logger.Log($"[StreamPipe] Error serving alert segment {fileName}: {ex.Message}", Logger.LogLevel.Debug);
            }
        }

        /// <summary>
        /// Inserts the alert injection block into an HLS playlist, handling
        /// #EXT-X-ENDLIST positioning and newline hygiene.
        /// </summary>
        private static string InjectAlertIntoHlsPlaylist(string content, string injectionBlock)
        {
            bool hadEndList = false;
            string endListTag = "#EXT-X-ENDLIST";
            int endListIdx = content.LastIndexOf(endListTag, StringComparison.OrdinalIgnoreCase);
            if (endListIdx >= 0)
            {
                hadEndList = true;
                content = content.Substring(0, endListIdx).TrimEnd('\r', '\n');
            }

            if (content.Length > 0 && content[content.Length - 1] != '\n')
                content += "\n";

            var sb = new StringBuilder(content.Length + injectionBlock.Length + 32);
            sb.Append(content);
            sb.Append(injectionBlock);
            if (hadEndList)
                sb.AppendLine(endListTag);

            return sb.ToString();
        }

        /// <summary>
        /// Sends a simple HTTP error response and closes the connection.
        /// </summary>
        private static async Task SendHttpError(NetworkStream stream, int statusCode, string reason, CancellationToken ct)
        {
            try
            {
                string resp = $"HTTP/1.1 {statusCode} {reason}\r\nConnection: close\r\nContent-Length: 0\r\n\r\n";
                byte[] bytes = Encoding.ASCII.GetBytes(resp);
                await stream.WriteAsync(bytes, 0, bytes.Length, ct);
            }
            catch { }
        }

        // ────────────────────────────────────────────────────────────────────
        // HLS alert segment preparation (FFmpeg)
        // ────────────────────────────────────────────────────────────────────

        /// <summary>
        /// Segments the alert .ts file into HLS-sized chunks using FFmpeg, stores them
        /// in a temp directory, and builds the injection block. Called in background
        /// when TriggerAlertSplice fires. After the alert duration + grace period,
        /// the temp directory is cleaned up automatically.
        /// </summary>
        private async Task PrepareAlertHlsSegmentsAsync(string tsPath, double durationSeconds)
        {
            try
            {
                // Clean up any previous alert segments
                CleanupAlertHlsDir();

                string tempDir = Path.Combine(Path.GetTempPath(), $"wsg_hls_pipe_{DateTime.UtcNow:yyyyMMddHHmmss}");
                Directory.CreateDirectory(tempDir);

                // Segment using FFmpeg (mux copy, no re-encode)
                string ffmpegPath = FFmpegLocator.GetFFmpegPath();
                if (!File.Exists(ffmpegPath)) ffmpegPath = "ffmpeg";

                string playlistPath = Path.Combine(tempDir, "eas_playlist.m3u8");
                string segmentPattern = Path.Combine(tempDir, $"{AlertHlsSegmentPrefix}%06d.ts");

                string args =
                    $"-y -i \"{tsPath}\" -c copy " +
                    $"-f hls -hls_time 4 " +
                    $"-hls_segment_filename \"{segmentPattern}\" " +
                    $"-hls_flags independent_segments " +
                    $"-hls_list_size 0 " +
                    $"\"{playlistPath}\"";

                Logger.Log($"[StreamPipe] HLS: segmenting alert {Path.GetFileName(tsPath)} into 4s chunks", Logger.LogLevel.Debug);

                var psi = new ProcessStartInfo
                {
                    FileName = ffmpegPath,
                    Arguments = args,
                    UseShellExecute = false,
                    CreateNoWindow = true,
                    RedirectStandardError = true,
                    RedirectStandardOutput = true
                };

                using var process = Process.Start(psi);
                if (process == null)
                {
                    Logger.Log("[StreamPipe] HLS: failed to start ffmpeg for segmentation.", Logger.LogLevel.Error);
                    return;
                }

                var stderrTask = process.StandardError.ReadToEndAsync();
                bool exited = await Task.Run(() => process.WaitForExit(60000));
                if (!exited)
                {
                    try { process.Kill(); } catch { }
                    Logger.Log("[StreamPipe] HLS: ffmpeg segmentation timed out (60s).", Logger.LogLevel.Error);
                    return;
                }

                if (process.ExitCode != 0)
                {
                    string stderr = await stderrTask;
                    Logger.Log($"[StreamPipe] HLS: ffmpeg segmentation failed (exit {process.ExitCode}): {stderr[..Math.Min(stderr.Length, 400)]}", Logger.LogLevel.Error);
                    return;
                }

                // Parse the generated playlist to get segment filenames and durations
                var segments = ParseHlsPlaylistFile(playlistPath, tempDir);
                if (segments.Count == 0)
                {
                    Logger.Log("[StreamPipe] HLS: ffmpeg produced no segments — HLS injection disabled for this alert.", Logger.LogLevel.Warning);
                    return;
                }

                // Build the injection block
                var sb = new StringBuilder();
                sb.AppendLine("#EXT-X-DISCONTINUITY");
                foreach (var (fileName, dur) in segments)
                {
                    sb.AppendLine($"#EXTINF:{dur.ToString("F6", CultureInfo.InvariantCulture)},");
                    sb.AppendLine(fileName);
                }
                sb.AppendLine("#EXT-X-DISCONTINUITY");

                // Publish — all fields set atomically from the caller's perspective
                // because each is a volatile write
                _alertHlsDir = tempDir;
                _alertHlsInjectionBlock = sb.ToString();
                Interlocked.Exchange(ref _alertHlsExpiryTicks, DateTime.UtcNow.AddSeconds(durationSeconds + 30).Ticks);

                Logger.Log($"[StreamPipe] ✓ HLS alert segments ready: {segments.Count} chunk(s) in {tempDir}", Logger.LogLevel.Info);

                // Schedule cleanup after expiry + grace period
                _ = Task.Run(async () =>
                {
                    await Task.Delay(TimeSpan.FromSeconds(durationSeconds + 90));
                    CleanupAlertHlsDir();
                });
            }
            catch (Exception ex)
            {
                Logger.Log($"[StreamPipe] HLS segment preparation failed: {ex.Message}", Logger.LogLevel.Warning);
            }
        }

        /// <summary>
        /// Parses a generated HLS playlist to extract segment filenames and durations.
        /// </summary>
        private static List<(string FileName, double Duration)> ParseHlsPlaylistFile(string playlistPath, string baseDir)
        {
            var result = new List<(string, double)>();
            if (!File.Exists(playlistPath)) return result;

            string[] lines = File.ReadAllLines(playlistPath);
            double nextDur = 0;

            for (int i = 0; i < lines.Length; i++)
            {
                string line = lines[i].Trim();
                if (line.StartsWith("#EXTINF:", StringComparison.OrdinalIgnoreCase))
                {
                    string durStr = line.Substring(8).TrimEnd(',');
                    double.TryParse(durStr, NumberStyles.Float, CultureInfo.InvariantCulture, out nextDur);
                }
                else if (!line.StartsWith("#") && !string.IsNullOrWhiteSpace(line) && nextDur > 0)
                {
                    string segPath = Path.Combine(baseDir, line);
                    if (File.Exists(segPath))
                        result.Add((line, nextDur));
                    nextDur = 0;
                }
            }

            return result;
        }

        /// <summary>
        /// Cleans up the temporary HLS alert segment directory and resets state.
        /// </summary>
        private void CleanupAlertHlsDir()
        {
            string? dir = _alertHlsDir;
            _alertHlsDir = null;
            _alertHlsInjectionBlock = null;
            Interlocked.Exchange(ref _alertHlsExpiryTicks, 0);

            if (dir != null)
            {
                try
                {
                    if (Directory.Exists(dir))
                        Directory.Delete(dir, true);
                    Logger.Log($"[StreamPipe] HLS: cleaned up alert segments in {dir}", Logger.LogLevel.Debug);
                }
                catch (Exception ex)
                {
                    Logger.Log($"[StreamPipe] HLS: cleanup failed for {dir}: {ex.Message}", Logger.LogLevel.Debug);
                }
            }
        }

        /// <summary>
        /// Builds a PID remap table: alert file PIDs → upstream (Tunarr) PIDs.
        /// Maps PMT PID, video PID(s), audio PID(s), and PCR PID.
        /// Currently unused but retained for future PID-remapping splice mode.
        /// </summary>
        private static Dictionary<int, int> BuildPidRemapTable(UpstreamPidMap alertPids, UpstreamPidMap upstreamPids)
        {
            var remap = new Dictionary<int, int>();

            // Don't remap if we haven't learned the upstream PIDs yet
            if (!upstreamPids.IsLearned) return remap;
            if (!alertPids.IsLearned) return remap;

            // Remap PMT PID
            if (alertPids.PmtPid > 0 && upstreamPids.PmtPid > 0 && alertPids.PmtPid != upstreamPids.PmtPid)
                remap[alertPids.PmtPid] = upstreamPids.PmtPid;

            // Remap video PID
            if (alertPids.VideoPid > 0 && upstreamPids.VideoPid > 0 && alertPids.VideoPid != upstreamPids.VideoPid)
                remap[alertPids.VideoPid] = upstreamPids.VideoPid;

            // Remap audio PID
            if (alertPids.AudioPid > 0 && upstreamPids.AudioPid > 0 && alertPids.AudioPid != upstreamPids.AudioPid)
                remap[alertPids.AudioPid] = upstreamPids.AudioPid;

            // Remap PCR PID (often same as video, but could be separate)
            if (alertPids.PcrPid > 0 && upstreamPids.PcrPid > 0 && alertPids.PcrPid != upstreamPids.PcrPid)
            {
                if (!remap.ContainsKey(alertPids.PcrPid))
                    remap[alertPids.PcrPid] = upstreamPids.PcrPid;
            }

            return remap;
        }

        /// <summary>
        /// Rewrites a single TS packet in-place: updates continuity counter for its PID
        /// and offsets any PTS/DTS/PCR timestamps.
        /// </summary>
        private static void RewritePacket(
            byte[] buffer,
            int offset,
            ConcurrentDictionary<int, int> ccTracker,
            long tickOffset)
        {
            int pid = MpegTsHelper.GetPid(buffer, offset);
            if (pid == MpegTsHelper.PidNull) return;

            // ── Continuity counter ──────────────────────────────────────
            if (MpegTsHelper.HasPayload(buffer, offset))
            {
                int nextCc = ccTracker.AddOrUpdate(pid,
                    _ => 0,
                    (_, prev) => (prev + 1) & 0x0F);
                MpegTsHelper.SetContinuityCounter(buffer, offset, nextCc);
            }

            // ── PCR offset ──────────────────────────────────────────────
            if (tickOffset != 0 && MpegTsHelper.HasPcr(buffer, offset))
            {
                long pcr = MpegTsHelper.GetPcrBase(buffer, offset);
                if (pcr >= 0)
                    MpegTsHelper.SetPcrBase(buffer, offset, pcr + tickOffset);
            }

            // ── PTS/DTS offset ──────────────────────────────────────────
            if (tickOffset != 0)
            {
                MpegTsHelper.OffsetTimestamps(buffer, offset, tickOffset);
            }
        }

